CREATE TABLE IF NOT EXISTS books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    author VARCHAR(200) NOT NULL,
    isbn VARCHAR(20) NOT NULL,
    total_copies INTEGER NOT NULL,
    available_copies INTEGER NOT NULL,
    version BIGINT,
    CONSTRAINT uk_books_isbn UNIQUE (isbn)
);

CREATE TABLE IF NOT EXISTS members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    email VARCHAR(200) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    CONSTRAINT uk_members_email UNIQUE (email)
);

ALTER TABLE members ADD COLUMN IF NOT EXISTS password_hash VARCHAR(100);

CREATE TABLE IF NOT EXISTS loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    book_id BIGINT NOT NULL,
    borrowed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    due_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    returned_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_loans_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_loans_book FOREIGN KEY (book_id) REFERENCES books (id)
);

CREATE INDEX IF NOT EXISTS idx_loans_member ON loans (member_id);

CREATE TABLE IF NOT EXISTS library_metric_counters (
    metric_name VARCHAR(100) NOT NULL,
    code VARCHAR(50) NOT NULL DEFAULT '',
    count BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (metric_name, code)
);

CREATE TABLE IF NOT EXISTS library_metric_timers (
    metric_name VARCHAR(100) PRIMARY KEY,
    total_ms BIGINT NOT NULL DEFAULT 0,
    sample_count BIGINT NOT NULL DEFAULT 0
);
